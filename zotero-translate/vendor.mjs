// Wraps the unmodified Zotero translators (MARC, MARCXML) into ES modules, so
// they can run without eval (forbidden in MV3). Usage:
//   node zotero-translate/vendor.mjs [translatorsDir]
import { readFileSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const srcDir = process.argv[2] || join(homedir(), "Zotero", "translators");

for (const name of ["MARC", "MARCXML"]) {
  const source = readFileSync(join(srcDir, `${name}.js`), "utf8");
  const end = source.indexOf("/** BEGIN TEST CASES **/");
  const code = end === -1 ? source : source.slice(0, end);
  const headerEnd = code.indexOf("\n}") + 2;
  const header = JSON.parse(code.slice(0, headerEnd));
  writeFileSync(
    join(here, "translators", `${name}.gen.js`),
    `// Generated by vendor.mjs from the Zotero translator "${header.label}" (${header.translatorID}), AGPL-3.0. Do not edit.
export default function (Zotero, ZU) {
${code.slice(headerEnd)}
return { exports: typeof exports === "undefined" ? undefined : exports, doImport };
}
`,
  );
}
